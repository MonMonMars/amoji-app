const CADENCE = ['burst', 'aside', 'lilt', 'cheer'] as const;

function fill(template: string, bits: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => bits[key] ?? '');
}

export function voiceCatchphrase(voice: VoiceId, motif: MotifId, frame: number, lang: Lang): string {
  const patterns = CATCH[voice][lang];
  const pattern = patterns[Math.abs(frame) % patterns.length]!;
  return fill(pattern, { noun: LEX[motif][lang].noun });
}

export function voiceCatchphrases(voice: VoiceId, motif: MotifId, frame: number, lang: Lang): string[] {
  const patterns = CATCH[voice][lang];
  const noun = LEX[motif][lang].noun;
  return patterns.map((_, i) => fill(patterns[(i + Math.abs(frame)) % patterns.length]!, { noun }));
}

export function voiceTone(voice: VoiceId, motif: MotifId, frame: number, blurb: string): string {
  const cadence = CADENCE[Math.abs(frame) % CADENCE.length]!;
  return `${blurb}; ${motif} on the mind; ${cadence} cadence`;
}

/** A finished motif sentence, so the line opens clearly and stays unique per character. */
const MOTIF_LEAD: Record<Lang, string> = {
  en: 'I like {noun}.',
  yue: '我鍾意{noun}。',
  zh: '我喜欢{noun}。',
  ja: '{noun}が好き。',
};

function withLead(lang: Lang, noun: string, line: string): string {
  return `${fill(MOTIF_LEAD[lang], { noun })} ${line}`.replace(/\s+/g, ' ').trim();
}

function renderPool(
  voice: VoiceId,
  motif: MotifId,
  frame: number,
  lang: Lang,
  bodies: readonly string[],
  extra: Record<string, string>,
): string[] {
  const lex = LEX[motif][lang];
  const wrap = WRAP[voice][lang][Math.abs(frame) % FRAME_COUNT]!;
  const bits = { noun: lex.noun, verb: lex.verb, thing: lex.thing, ...extra };
  return bodies.map((body) => withLead(lang, lex.noun, fill(wrap, { body: fill(body, bits) })));
}

export function voiceIdleLines(voice: VoiceId, motif: MotifId, frame: number, lang: Lang): string[] {
  // The body is the line. The old catchphrase wrap ("Cheer time! tea sunshine!")
  // made idle talk sound like nonsense. Frame rotates which line leads so two
  // companions who share a voice still differ.
  const lex = LEX[motif][lang];
  const lines = IDLE[voice][lang].map((body) => fill(body, { noun: lex.noun, verb: lex.verb, thing: lex.thing }));
  const shift = Math.abs(frame) % lines.length;
  return lines.slice(shift).concat(lines.slice(0, shift));
}

export function voicePokeLines(voice: VoiceId, motif: MotifId, frame: number, lang: Lang, zone: string): string[] {
  const word = ZONE[zone]?.[lang] ?? ZONE.side![lang];
  return renderPool(voice, motif, frame, lang, POKE[voice][lang], { zone: word });
}

export function voiceOpening(voice: VoiceId, motif: MotifId, frame: number, lang: Lang, name: string): string {
  // frame keeps each cached companion on their own opener slot. The line
  // itself is a plain greeting: who they are, what they like, an invite.
  void frame;
  const noun = LEX[motif][lang].noun;
  return fill(OPENING[voice][lang], { name, noun });
}

